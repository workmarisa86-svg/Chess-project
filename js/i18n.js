// Spanish algebraic notation: R = Rey, D = Dama, T = Torre, A = Alfil, C = Caballo.
const SAN_LETTERS_ES = { K: 'R', Q: 'D', R: 'T', B: 'A', N: 'C' };
function localizeSan(san, lang) {
  if (lang !== 'es') return san;
  return san.replace(/[KQRBN]/g, ch => SAN_LETTERS_ES[ch]);
}
